/* ============================================================
   CODING-STARTER-LISTS.JS — the list ADT coursework, as practice
   ------------------------------------------------------------
   Three programs built from the handout files: an array-backed list, the same
   thing as a linked list, and the array one again with the later tasks added.

   THESE ARE THE ONE PLACE IN THE PACK WITH STARTER CODE. Everywhere else the
   editor opens empty, because those exercises are "write this program". These
   are not: the handout gives you a header with the display functions already
   written and the rest stubbed out, and the exercise IS filling in the stubs.
   Taking the scaffolding away would be a different, worse exercise.

   TWO FILES EACH, which is what makes them work at all: main.c includes
   "ArrayList.h", and Run Code links a header its main file includes. The
   header holds the struct definitions and the function bodies, so including
   it is the whole program -- that is how the handout is arranged and it is
   left that way on purpose.

   The reference is a complete implementation of every stub. It is what the
   boss bar measures against and what Check Code grades by, and its output is
   where the expected test output came from -- generated by running it, never
   typed out by hand.
   ============================================================ */

