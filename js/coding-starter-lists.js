/* The one test both list programs share.

   They are checked against the SAME string because a correct array list and a
   correct linked list must print exactly the same thing -- the driver does not
   know which one it is talking to. If an edit ever makes them diverge, one of
   these two tests fails and says so.

   Version 2 gets no output test: see coding-starter-lists-expected.js for why
   a NUL byte in the expected output is not worth defending. */
function _cslRunTest() {
  if (typeof CSL_EXPECTED === 'undefined') return [];
  return [{ name: 'populates, displays and deletes', stdin: '', expected: CSL_EXPECTED.listRun }];
}

/** A two-file program: the driver, and the header it includes. */
function _cslProgram(id, title, description, driverKey, headerName, headerKey, tests) {
  return {
    id: 'starter-' + id,
    title: title,
    parentId: 'starter-folder-8',
    description: description,
    createdAt: 1700000000000,
    variants: [{
      id: 'starter-' + id + '-v1',
      name: 'C',
      description: '',
      starterCode: CSL_TEMPLATES[driverKey],
      code: CSL_SOLUTIONS[driverKey],
      activeFileIndex: 0,
      files: [
        { id: 'starter-' + id + '-f1', name: 'main', ext: '.c',
          starterCode: CSL_TEMPLATES[driverKey], code: CSL_SOLUTIONS[driverKey] },
        { id: 'starter-' + id + '-f2', name: headerName, ext: '.h',
          starterCode: CSL_TEMPLATES[headerKey], code: CSL_SOLUTIONS[headerKey] }
      ],
      samples: [],
      tests: tests || [],
      minRequirements: []
    }]
  };
}

