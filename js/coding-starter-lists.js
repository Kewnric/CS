const _CSL_ARR_BODY =
  'void displayList(List A)\n{\n    int x;\n\n    displayHeader();\n\n'
+ '    for (x = 0; x < A.count; x++) {\n        displayStudent(A.studs[x]);\n    }\n\n'
+ '    printf("\\n\\nList has %d elements:", A.count);\n}\n\n'
+ 'void initList(List *A)\n{\n    A->count = 0;\n}\n\n'
+ 'void insertLast(List *A, studtype S)\n{\n'
+ '    if (A->count < ARR_LENGTH) {\n'
+ '        A->studs[A->count] = S;\n        A->count++;\n'
+ '    } else {\n'
+ '        printf("\\nList is full. Cannot insert Element with ID %s", S.ID);\n    }\n}\n\n'
+ 'void deleteElem(List *A, char ID[])\n{\n    int x, found = -1;\n\n'
+ '    for (x = 0; x < A->count && found == -1; x++) {\n'
+ '        if (strcmp(A->studs[x].ID, ID) == 0) {\n            found = x;\n        }\n    }\n\n'
+ '    if (found == -1) {\n'
+ '        printf("\\nElement with ID %s is not found", ID);\n'
+ '    } else {\n'
+ '        for (x = found; x < A->count - 1; x++) {\n'
+ '            A->studs[x] = A->studs[x + 1];\n        }\n        A->count--;\n    }\n}\n';

const _CSL_LL_BODY =
  'void displayList(List A)\n{\n    List trav;\n    int count = 0;\n\n    displayHeader();\n\n'
+ '    for (trav = A; trav != NULL; trav = trav->link) {\n'
+ '        displayStudent(trav->stud);\n        count++;\n    }\n\n'
+ '    printf("\\n\\nList has %d elements:", count);\n}\n\n'
+ 'void initList(List *A)\n{\n    *A = NULL;\n}\n\n'
+ 'void insertLast(List *A, studtype S)\n{\n    List *trav;\n'
+ '    List newNode = malloc(sizeof(struct node));\n\n'
+ '    if (newNode == NULL) {\n'
+ '        printf("\\nMemory Allocation Error. Cannot insert Element with ID %s", S.ID);\n'
+ '    } else {\n        newNode->stud = S;\n        newNode->link = NULL;\n\n'
+ '        for (trav = A; *trav != NULL; trav = &(*trav)->link) {\n        }\n'
+ '        *trav = newNode;\n    }\n}\n\n'
+ 'void deleteElem(List *A, char ID[])\n{\n    List *trav;\n    List temp;\n\n'
+ '    for (trav = A; *trav != NULL && strcmp((*trav)->stud.ID, ID) != 0;\n'
+ '         trav = &(*trav)->link) {\n    }\n\n'
+ '    if (*trav == NULL) {\n'
+ '        printf("\\nElement with ID %s is not found", ID);\n'
+ '    } else {\n        temp = *trav;\n        *trav = temp->link;\n        free(temp);\n    }\n}\n';

